"""Bake verified greatdocbrown CC0 tiles into the original-game sprite adapter.

Original integration work: djultra64. Source artwork: greatdocbrown, CC0-1.0.
Exact crops, nearest-neighbor fitting and declared stick/direction composition only.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image
PINNED={
 'gdb-keyboard-2.png':'76667a5df663df494c9b6b87beda1c1f3d7fef8b47fc41688b12062290dafb66',
 'gdb-playstation-3.png':'cf054306e26fbce7c9d7e960f0e9a9011804fa3a4b87ddc64427e347138140d2',
 'gdb-xbox-2.png':'efddfa9252c0b3ac20c07f2b07c2d7b8ae209de4e17f80b0e4081af1a9cecf77',
 'gdb-switch-2.png':'7a6aec560b5ec1d0b687c110dcf305075e8a6fb31b3fb54a4bc5f5d6a5c6f5c5',
}
FAMILIES={'Xbox','PlayStation','Nintendo','Keyboard'}
def prepare(assets:Path,output:Path,check=False)->dict:
 images={}
 for name,digest in PINNED.items():
  path=assets/name
  if path.is_symlink() or hashlib.sha256(path.read_bytes()).hexdigest()!=digest:
   raise ValueError('Official artist source digest mismatch: '+name)
  images[name]=Image.open(path).convert('RGBA')
 manifest=json.loads((assets/'tiles.json').read_text())
 if manifest['schema_version']!=1:raise ValueError('Unsupported tile manifest')
 tiles=[];tile_ids={};mappings=[];keys=set();colors=[];color_ids={}
 for entry in manifest['tiles']:
  family=entry['family'];label=entry['label'];rect=entry['rect'];sheet=entry['sheet']
  if family not in FAMILIES or sheet not in images or len(rect)!=4 or any(type(v)!=int for v in rect):raise ValueError('Invalid artist tile')
  x,y,w,h=rect;image=images[sheet]
  if min(x,y)<0 or min(w,h)<1 or x+w>image.width or y+h>image.height:raise ValueError('Artist tile outside sheet')
  crop=image.crop((x,y,x+w,y+h))
  if max(w,h)>16:
   scale=16/max(w,h);crop=crop.resize((max(1,round(w*scale)),max(1,round(h*scale))),Image.Resampling.NEAREST)
  tile=Image.new('RGBA',(16,16))
  if 'derivative' in entry:
   if entry['derivative']!='right-stick-direction' or (w,h)!=(16,16):raise ValueError('Unsupported artist derivative')
   direction=entry['direction'];ds=direction['sheet'];dr=direction['rect']
   if ds not in images or len(dr)!=4 or any(type(v)!=int for v in dr):raise ValueError('Invalid direction source')
   dx,dy,dw,dh=dr;di=images[ds]
   if min(dx,dy)<0 or (dw,dh)!=(16,16) or dx+dw>di.width or dy+dh>di.height:raise ValueError('Direction outside sheet')
   tile.alpha_composite(crop.resize((12,12),Image.Resampling.NEAREST),(0,0))
   tile.alpha_composite(di.crop((dx,dy,dx+dw,dy+dh)).resize((8,8),Image.Resampling.NEAREST),(8,8))
  else:tile.paste(crop,((16-crop.width)//2,(16-crop.height)//2))
  raw=tile.tobytes()
  if not any(raw[n] for n in range(3,len(raw),4)):raise ValueError('Empty artist tile')
  if raw not in tile_ids:
   tile_ids[raw]=len(tiles);indices=[]
   for color in tile.getdata():
    if color not in color_ids:color_ids[color]=len(colors);colors.append(color)
    indices.append(color_ids[color])
   tiles.append(indices)
  for name in [label]+entry.get('aliases',[]):
   if not isinstance(name,str) or not name or len(name)>64 or (family,name) in keys:raise ValueError('Invalid/duplicate physical glyph key')
   keys.add((family,name));mappings.append((family,name,tile_ids[raw]))
 if len(colors)>256:raise ValueError('Artist atlas exceeds indexed color capacity')
 lines=['// Generated by tools.prepare_prompt_glyphs. Do not redraw source artwork.',
  '// Artist: greatdocbrown. https://greatdocbrown.itch.io/gamepad-ui CC0-1.0.',
  '// Original integration work: djultra64.',
  'struct ArtworkGlyph {PromptGlyphFamily family;std::string_view label;uint16_t tile;};',
  f'constexpr std::array<uint32_t,{len(colors)}> artwork_colors{{{{']
 lines += ['    '+','.join(f'0x{r:02X}{g:02X}{b:02X}{a:02X}u' for r,g,b,a in colors),'}};',
  f'constexpr std::array<std::array<uint8_t,256>,{len(tiles)}> artwork_tiles{{{{']
 for tile in tiles:lines.append('    {{'+','.join(str(v) for v in tile)+'}},')
 lines+=['}};',f'constexpr std::array<ArtworkGlyph,{len(mappings)}> artwork_glyphs{{{{']
 for family,label,index in mappings:lines.append('    {PromptGlyphFamily::'+family+','+json.dumps(label,ensure_ascii=False)+','+str(index)+'},')
 lines+=['}};',''];data='\n'.join(lines).encode()
 if output.is_symlink():raise ValueError('Refusing symlink output')
 if output.exists():
  if output.read_bytes()!=data:raise ValueError('Generated glyph output differs; review before replacing')
 elif check:raise ValueError('Generated glyph output missing')
 else:
  output.parent.mkdir(parents=True,exist_ok=True);output.write_bytes(data)
 return dict(artist='greatdocbrown',license='CC0-1.0',glyph_count=len(mappings),tile_count=len(tiles),source_sha256=PINNED,output_sha256=hashlib.sha256(data).hexdigest())
def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--assets',type=Path,required=True);parser.add_argument('--output',type=Path,required=True);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 print(json.dumps(prepare(args.assets,args.output,args.check),indent=2))
if __name__=='__main__':main()
